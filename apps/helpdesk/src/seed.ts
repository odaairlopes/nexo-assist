function ticket(partial: Omit<Ticket, 'events' | 'resolvedAt' | 'queue' | 'subcategory'> & Partial<Ticket>): Ticket {
  return {
    queue: 'N1',
    subcategory: null,
    resolvedAt: null,
    events: [{ at: partial.createdAt, kind: 'created', author: 'Formulário', text: 'Chamado aberto' }],
    ...partial,
  };
}

